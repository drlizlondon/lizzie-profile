#!/usr/bin/env node
'use strict';

/* generate-analytics-config.js — writes public/analytics-config.js from the
   LIZPROFILE_GA4_MEASUREMENT_ID environment variable at build time.

   Why this exists: lp-consent.js (the consent-gated analytics loader) must
   stay a plain, blockable static file — never bundled by Vite — so a
   privacy tool or ad blocker can inspect and block it like any other
   third-party script. That means it cannot read `import.meta.env` (that
   substitution only applies to Vite-processed modules). This script is the
   env-to-static bridge: it runs once before `npm run dev` / `npm run build`
   (wired as the `predev` / `prebuild` npm lifecycle scripts in
   package.json) and writes a tiny generated file that lp-consent.js reads
   as a plain global.

   public/analytics-config.js is GITIGNORED and regenerated on every run —
   never commit it, never hand-edit it. The GA4 measurement id is not a
   secret (it appears in plain sight in every analytics request a browser
   makes), but reading it from an environment variable rather than
   hardcoding it in committed source means the id can differ per Vercel
   environment (production vs. preview) without a code change, and no id
   is baked into git history.

   With no LIZPROFILE_GA4_MEASUREMENT_ID set (local dev by default, or a
   preview deploy with the env var not configured), this writes an empty
   id. lp-consent.js treats an empty id as "analytics not configured for
   this environment" and stays completely inert — no banner, no requests,
   nothing. */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/** @param {string | undefined} [measurementId] */
export function renderAnalyticsConfig(measurementId) {
  const id = measurementId || '';
  return (
    '/* GENERATED by scripts/generate-analytics-config.js — do not edit by hand\n' +
    '   or commit this file. Regenerated on every `npm run dev` / `npm run build`\n' +
    '   from the LIZPROFILE_GA4_MEASUREMENT_ID environment variable. */\n' +
    `window.__LIZPROFILE_GA4_MEASUREMENT_ID__ = ${JSON.stringify(id)};\n`
  );
}

function main() {
  const measurementId = process.env.LIZPROFILE_GA4_MEASUREMENT_ID || '';
  const here = dirname(fileURLToPath(import.meta.url));
  const outPath = join(here, '..', 'public', 'analytics-config.js');

  writeFileSync(outPath, renderAnalyticsConfig(measurementId));

  if (measurementId) {
    console.log('analytics-config.js written with a GA4 measurement id read from LIZPROFILE_GA4_MEASUREMENT_ID.');
  } else {
    console.log('analytics-config.js written WITHOUT a GA4 id (LIZPROFILE_GA4_MEASUREMENT_ID is not set) — analytics stays off.');
  }
}

// Only run when executed directly (not when imported by tests).
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
